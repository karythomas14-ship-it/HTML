let brickBag = [];

// random bag system
function getRandomBrick() {

    if (brickBag.length === 0) {

        brickBag = [0,1,2,3,4,5,6];

        for (
            let i = brickBag.length - 1;
            i > 0;
            i--
        ) {

            let j =
                Math.floor(
                    Math.random() * (i + 1)
                );

            [brickBag[i], brickBag[j]] =
            [brickBag[j], brickBag[i]];
        }
    }

    return brickBag.pop();
}